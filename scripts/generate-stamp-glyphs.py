#!/usr/bin/env python3
"""Regenerates `src-tauri/src/stamp_glyphs.rs` from a Noto Sans SC subset.

The built-in stamps need Chinese label text inside a PDF appearance stream.
PDFium's custom-appearance API installs only an opacity graphics state, not a
font resource, so the labels are baked as vector path operators. Keeping the
outlines in the crate (rather than loading a font at runtime) makes every stamp
self-contained and needs no font pipeline.

Usage:
    python3 scripts/generate-stamp-glyphs.py path/to/NotoSansSC-Bold-subset.woff2

The font is licensed under the SIL Open Font License 1.1; the license text is
committed as `src-tauri/assets/NotoSansSC-OFL.txt`. A WOFF2 subset containing
only the label characters can be fetched from the Google Fonts CSS API with
`text=` set to the labels below.
"""

import sys
from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

ART_W, ART_H = 600.0, 200.0
TEXT_INK_HEIGHT = 124.0
STAMPS = [
    ("APPROVED", "已批准"),
    ("DRAFT", "草稿"),
    ("CONFIDENTIAL", "机密"),
    ("REJECTED", "已拒绝"),
]
OUTPUT = Path(__file__).resolve().parent.parent / "src-tauri" / "src" / "stamp_glyphs.rs"

HEADER = """//! Vector outlines for the built-in stamp labels, in a {width:.0} x {height:.0} art box.
//!
//! Generated by `scripts/generate-stamp-glyphs.py` from Noto Sans SC Bold
//! (SIL Open Font License 1.1; see `assets/NotoSansSC-OFL.txt`). The glyphs
//! are baked as path operators so the appearance stream needs no font
//! resource: PDFium's custom appearance API only installs an opacity
//! graphics state, not fonts.
""".format(width=ART_W, height=ART_H)


def fmt(value):
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return text if text not in ("", "-0") else "0"


class PathPen(BasePen):
    """Collects glyph outlines as PDF path operators in font units."""

    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.ops = []
        self.points = []

    def _emit(self, op, *args):
        coordinates = " ".join(fmt(value) for value in args)
        self.ops.append(f"{coordinates} {op}".strip())

    def _note(self, *points):
        self.points.extend(points)

    def _moveTo(self, pt):
        self._note(pt)
        self._emit("m", *pt)

    def _lineTo(self, pt):
        self._note(pt)
        self._emit("l", *pt)

    def _curveToOne(self, pt1, pt2, pt3):
        self._note(pt1, pt2, pt3)
        self._emit("c", *pt1, *pt2, *pt3)

    def _qCurveToOne(self, pt1, pt2):
        # TrueType uses quadratic curves; PDF has cubics only.
        p0 = self._getCurrentPoint()
        c1 = (
            p0[0] + 2.0 / 3.0 * (pt1[0] - p0[0]),
            p0[1] + 2.0 / 3.0 * (pt1[1] - p0[1]),
        )
        c2 = (
            pt2[0] + 2.0 / 3.0 * (pt1[0] - pt2[0]),
            pt2[1] + 2.0 / 3.0 * (pt1[1] - pt2[1]),
        )
        self._note(c1, c2, pt2)
        self._emit("c", *c1, *c2, *pt2)

    def _closePath(self):
        self._emit("h")


def glyph_paths(font, glyph_set, text):
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    paths = []
    x_offset = 0.0
    for char in text:
        glyph_name = cmap[ord(char)]
        pen = PathPen(glyph_set)
        glyph_set[glyph_name].draw(pen)
        paths.append((x_offset, pen.ops, pen.points))
        x_offset += hmtx[glyph_name][0]
    return paths


def transform_ops(ops, scale, dx, dy):
    result = []
    for op in ops:
        parts = op.split(" ")
        command = parts[-1]
        numbers = [float(value) for value in parts[:-1]]
        moved = []
        for index in range(0, len(numbers), 2):
            moved.append(numbers[index] * scale + dx)
            moved.append(numbers[index + 1] * scale + dy)
        coordinates = " ".join(fmt(value) for value in moved)
        result.append(f"{coordinates} {command}".strip())
    return result


def rounded_rect(x0, y0, x1, y1, radius):
    r = radius
    return [
        f"{fmt(x0 + r)} {fmt(y0)} m",
        f"{fmt(x1 - r)} {fmt(y0)} l",
        f"{fmt(x1 - r + 0.5523 * r)} {fmt(y0)} "
        f"{fmt(x1)} {fmt(y0 + r - 0.5523 * r)} {fmt(x1)} {fmt(y0 + r)} c",
        f"{fmt(x1)} {fmt(y1 - r)} l",
        f"{fmt(x1)} {fmt(y1 - r + 0.5523 * r)} "
        f"{fmt(x1 - r + 0.5523 * r)} {fmt(y1)} {fmt(x1 - r)} {fmt(y1)} c",
        f"{fmt(x0 + r)} {fmt(y1)} l",
        f"{fmt(x0 + r - 0.5523 * r)} {fmt(y1)} "
        f"{fmt(x0)} {fmt(y1 - r + 0.5523 * r)} {fmt(x0)} {fmt(y1 - r)} c",
        f"{fmt(x0)} {fmt(y0 + r)} l",
        f"{fmt(x0)} {fmt(y0 + r - 0.5523 * r)} "
        f"{fmt(x0 + r - 0.5523 * r)} {fmt(y0)} {fmt(x0 + r)} {fmt(y0)} c",
        "h",
    ]


def build_art(font, text):
    glyph_set = font.getGlyphSet()
    paths = glyph_paths(font, glyph_set, text)
    xs = [point[0] + offset for offset, _, points in paths for point in points]
    ys = [point[1] for _, _, points in paths for point in points]
    min_x, max_x = min(xs), max(xs)
    min_y, max_y = min(ys), max(ys)
    ink_width = max_x - min_x
    ink_height = max_y - min_y
    scale = min(TEXT_INK_HEIGHT / ink_height, (ART_W - 120.0) / ink_width)
    dx = (ART_W - ink_width * scale) / 2.0 - min_x * scale
    dy = (ART_H - ink_height * scale) / 2.0 - min_y * scale

    ops = ["7 w"]
    # Double rounded frame, stamp style.
    ops.extend(rounded_rect(10, 10, ART_W - 10, ART_H - 10, 26))
    ops.append("S")
    ops.append("2.5 w")
    ops.extend(rounded_rect(26, 26, ART_W - 26, ART_H - 26, 16))
    ops.append("S")
    for offset, glyph_ops, _ in paths:
        ops.extend(transform_ops(glyph_ops, scale, dx + offset * scale, dy))
        ops.append("f")
    return "\n".join(ops)


def main():
    if len(sys.argv) != 2:
        sys.exit(f"usage: {sys.argv[0]} path/to/NotoSansSC-Bold-subset.woff2")
    font = TTFont(sys.argv[1])
    chunks = [HEADER]
    for const_name, text in STAMPS:
        chunks.append(f'pub(crate) const {const_name}: &str = r#"{build_art(font, text)}"#;\n')
    OUTPUT.write_text("\n".join(chunks))
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
