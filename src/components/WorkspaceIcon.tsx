export type WorkspaceIconName = keyof typeof icons;
export function WorkspaceIcon({
  name,
  className,
}: {
  name: WorkspaceIconName;
  className?: string;
}) {
  const Icon = icons[name];
  return (
    <Icon
      className={className ? `ws-icon ${className}` : "ws-icon"}
      size={20}
      strokeWidth={1.7}
      aria-hidden="true"
      focusable="false"
    />
  );
}
